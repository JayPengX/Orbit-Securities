// The language chosen in any Orbit app (kit orbit.mjs detectLang, 'orbit.lang'), else the phone's.
export function detectLocale() {
  try {
    const saved = globalThis.localStorage?.getItem('orbit.lang');
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {}
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language || ''];
  return languages.some(l => /^zh/i.test(l)) ? 'zh' : 'en';
}

export function makeT(locale) {
  return (key, vars) => {
    let s = STRINGS[locale][key] ?? STRINGS.zh[key] ?? key;
    if (vars && typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}

