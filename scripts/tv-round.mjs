// Builds public/lib/tvround.mjs: the TradingView icons in tvlogos.mjs that are a
// disc (a circle on a clear square) and the disc's colour, so the app fills
// their tile with it (no white or dark corners). Run it after tv-logos.mjs:
// `node scripts/tv-round.mjs`. It reads each SVG once with curl.
import { execFile } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { promisify } from 'node:util';

const run = promisify(execFile);
const src = readFileSync(new URL('../public/lib/tvlogos.mjs', import.meta.url), 'utf8');
const ids = [...new Set([...src.matchAll(/"[^"]+": "([^"]+)"/g)].flatMap(m => m[1].split('|')))].sort();
// The first shape: a full-size circle path (M0 9a9 9 0 …) or <circle r="9">, and its fill.
const discFill = svg => {
  const first = svg.replace(/<!--.*?-->/gs, '').match(/<svg[^>]*>\s*(<(?:path|circle)[^>]*>)/)?.[1] || '';
  const disc = /\bd="M0 9a9 9 0 /i.test(first) || (/<circle/.test(first) && /\br="9"/.test(first) && /\bcx="9"/.test(first));
  return disc ? first.match(/\bfill="(#[0-9a-f]{3,8})"/i)?.[1]?.toUpperCase() || null : null;
};
const round = {};
let next = 0;
let read = 0;
await Promise.all(
  Array.from({ length: 8 }, async () => {
    while (next < ids.length) {
      const id = ids[next++];
      for (let tries = 0; tries < 4; tries++) {
        try {
          const { stdout } = await run('curl', ['-sf', '-m', '20', `https://s3-symbol-logo.tradingview.com/${id}.svg`]);
          read++;
          const fill = discFill(stdout);
          if (fill) round[id] = fill;
          break;
        } catch {}
      }
    }
  })
);
if (read < ids.length * 0.9) throw new Error(`only ${read} of ${ids.length} icons read`);
const body = Object.keys(round)
  .sort()
  .map(id => `  ${JSON.stringify(id)}: ${JSON.stringify(round[id])}`)
  .join(',\n');
writeFileSync(
  new URL('../public/lib/tvround.mjs', import.meta.url),
  `// Generated by scripts/tv-round.mjs: TradingView icons that are a disc, and its colour.\nexport const TV_ROUND = {\n${body}\n};\n`
);
console.log(`${Object.keys(round).length} round of ${read} read (${ids.length} ids)`);
